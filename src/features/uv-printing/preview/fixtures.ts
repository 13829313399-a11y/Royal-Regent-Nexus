interface ReportSeed extends Partial<UvReport> {
  id: string
  business_date: BusinessDate
  shift: ShiftCode
  machine_id: Id
  product_id: Id
  source_kind: UvReport['source_kind']
  status: UvReport['status']
  quality: UvQuality
  worker_ids: Id[]
  notes?: string
  replaces_report_id?: Id | null
  correction_reason?: string
  allocation_total?: number
}

function seedReport(seed: ReportSeed): UvReport {
  const product = sampleProducts.find((candidate) => candidate.id === seed.product_id)
  const processVersion = product?.process_versions[0]
  const workers = seed.worker_ids
    .map((workerId) => sampleWorkers.find((worker) => worker.id === workerId))
    .filter((worker): worker is UvWorkerRef => Boolean(worker))
  const qualityStatus = seed.quality.pending_qty === seed.quality.reported_qty && seed.quality.reported_qty > 0
    ? 'pending'
    : seed.quality.pending_qty > 0 || seed.quality.semi_finished_qty > 0
      ? 'partial'
      : 'complete'

  return {
    ...entity(seed.id, at(seed.business_date, '07:00'), seed.status === 'corrected' ? 2 : 1),
    business_date: seed.business_date,
    shift: seed.shift,
    shift_template_version_id: DEFAULT_SHIFT_TEMPLATES[seed.shift].versionId,
    machine_id: seed.machine_id,
    product_id: seed.product_id,
    process_version_id: processVersion?.id ?? '',
    product_no: product?.product_no ?? '',
    product_name: product?.name ?? '',
    reported_qty: seed.quality.reported_qty,
    good_qty: seed.quality.good_qty,
    defective_qty: seed.quality.defective_qty,
    pending_qty: seed.quality.pending_qty,
    semi_finished_qty: seed.quality.semi_finished_qty,
    source_kind: seed.source_kind,
    status: seed.status,
    quality_status: qualityStatus,
    worker_ids: seed.worker_ids,
    worker_names: workers.map((worker) => worker.display_name),
    notes: seed.notes ?? '',
    replaces_report_id: seed.replaces_report_id ?? null,
    correction_reason: seed.correction_reason ?? '',
    allocation_total: seed.allocation_total ?? 0,
  }
}

