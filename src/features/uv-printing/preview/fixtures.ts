function job(
  id: string,
  input: Omit<UvPrintJob, keyof UvEntity | 'factory_id' | 'candidates' | 'ink_by_color'> & {
    candidates?: UvPrintJob['candidates']
    ink_by_color?: UvPrintJob['ink_by_color']
  },
): UvPrintJob {
  const { candidates, ink_by_color: inkByColor, ...rest } = input
  return {
    ...entity(id, at(input.started_at ? input.started_at.slice(0, 10) : SAMPLE_BUSINESS_DATE, '08:00')),
    ...rest,
    id,
    candidates: candidates ?? [],
    ink_by_color: inkByColor ?? [],
  }
}

