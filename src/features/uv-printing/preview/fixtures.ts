/** 报表使用的稳定错开日期，用于构造按日聚合。 */
export function sampleOffsetDate(offset: number): BusinessDate {
  const base = SAMPLE_BUSINESS_DATE
  const [year, month, day] = base.split('-').map(Number)
  const date = new Date(Date.UTC(year, (month ?? 1) - 1, day ?? 1))
  date.setUTCDate(date.getUTCDate() + offset)
  const month2 = String(date.getUTCMonth() + 1).padStart(2, '0')
  const day2 = String(date.getUTCDate()).padStart(2, '0')
  return `${date.getUTCFullYear()}-${month2}-${day2}`
}
