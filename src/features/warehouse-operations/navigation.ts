export interface WarehouseView {
  id: string
  title: string
  description: string
  columns: string[]
  actions: string[]
}
export interface WarehouseSection {
  path: string
  title: string
  description: string
  views: WarehouseView[]
}
export interface WarehouseWorkspace {
  id: string
  title: string
  summary: string
  flow: string[]
  sections: WarehouseSection[]
  pending: { title: string; description: string; section: string; view: string }[]
}
const view = (id: string, title: string, description: string, columns: string, actions = ''): WarehouseView => ({
  id, title, description, columns: columns.split('｜'), actions: actions ? actions.split('｜') : [],
})
const section = (path: string, title: string, description: string, views: WarehouseView[]): WarehouseSection => ({ path, title, description, views })

