import { readFileSync } from 'node:fs'
import { join } from 'node:path'
import { describe, expect, it } from 'vitest'

const read = (path: string) => readFileSync(join(process.cwd(), path), 'utf8')
const routerSource = read('src/router/index.ts')
const enterpriseSource = read('src/data/enterpriseMock.ts')
const viewSource = read('src/views/InternalQuoteDeskView.vue')
const workbenchSource = read('src/components/modules/sales/SalesModuleWorkbench.vue')
const homeSource = read('src/components/modules/sales/internal-quote/InternalQuoteHome.vue')
const createDialogSource = read('src/components/modules/sales/internal-quote/InternalQuoteCreateDialog.vue')
const collaborationSource = read('src/components/modules/sales/internal-quote/InternalQuoteCollaboration.vue')
const activitySource = read('src/components/modules/sales/internal-quote/InternalQuoteActivityPanel.vue')
const sectionEditorSource = read('src/components/modules/sales/internal-quote/InternalQuoteSectionEditor.vue')
const sectionFormSource = read('src/components/modules/sales/internal-quote/InternalQuoteSectionForm.vue')
const summarySource = read('src/components/modules/sales/internal-quote/InternalQuoteSummary.vue')
const exportSource = read('src/components/modules/sales/internal-quote/InternalQuoteExportSummary.vue')
const apiSource = read('src/api/internalQuote.ts')
const storeSource = read('src/stores/internalQuoteDesk.ts')

describe('internal quote desk frontend layout', () => {
  it('registers the new module under the business department without replacing customer conversion', () => {
    expect(enterpriseSource).toContain("id: 'internal-quote-desk'")
    expect(enterpriseSource).toContain("title: '内部报价台'")
    expect(enterpriseSource).toContain("route: '/modules/sales-business/internal-quote-desk'")
    expect(enterpriseSource).toContain('业务部与工程部建单')
    expect(enterpriseSource).toContain("id: 'customer-price-conversion'")
    expect(enterpriseSource).toContain("title: '客价转换台'")
    expect(viewSource).toContain('SalesModuleWorkbench')
    expect(viewSource).toContain('title="内部报价台"')
  })

  it('exposes the four staged frontend routes before the generic module route', () => {
    const internalQuoteRouteIndex = routerSource.indexOf("path: '/modules/sales-business/internal-quote-desk'")
    const genericModuleRouteIndex = routerSource.indexOf("path: '/modules/:department/:module'")
    expect(internalQuoteRouteIndex).toBeGreaterThan(-1)
    expect(internalQuoteRouteIndex).toBeLessThan(genericModuleRouteIndex)
    expect(routerSource).toContain("name: 'internal-quote-desk-home'")
    expect(routerSource).toContain("name: 'internal-quote-collaboration'")
    expect(routerSource).toContain("name: 'internal-quote-summary'")
    expect(routerSource).toContain("name: 'internal-quote-export-summary'")
    const routeSource = routerSource.slice(internalQuoteRouteIndex, genericModuleRouteIndex)
    expect(routeSource).not.toContain('requiresAuth: false')
  })

  it('implements the confirmed creation, collaboration, browsing, release and export surfaces', () => {
    for (const text of ['新建内部报价', '复制报价', '业务部', '工程部', '搜索报价号']) expect(homeSource).toContain(text)
    for (const text of ['责任分段进度', '参考快照已冻结', '查看汇总与放行']) expect(collaborationSource).toContain(text)
    for (const text of ['Excel 预览导入', '预览不会修改正式数据', '申请不适用', '合法重开', '分段附件']) expect(sectionEditorSource).toContain(text)
    for (const text of ['材料与外购', '电子零件与子项', '注塑明细', '七类喷油工序', '搪胶成本明细', '车缝产品组', '装配与包装产品组', '出货场景']) expect(sectionFormSource).toContain(text)
    for (const text of ['协作评论', '业务操作时间线', '浏览记录', '短时间刷新会去重']) expect(activitySource).toContain(text)
    for (const text of ['汇总与最终放行', '分段放行状态', '最终提交人与最终放行人不得相同']) expect(summarySource).toContain(text)
    for (const text of ['内部报价导出汇总', '审批 revision 矩阵', '均由后端控制']) expect(exportSource).toContain(text)
  })

  it('matches the molding-sample interaction baseline for back navigation, motion and readable type', () => {
    expect(workbenchSource).toContain('sales-topbar-back')
    expect(workbenchSource).toContain('backTo?: string')
    expect(viewSource).toContain("label: '业务部模块'")
    expect(viewSource).toContain("label: '返回报价首页'")
    expect(viewSource).toContain("label: '返回协作页'")
    expect(viewSource).toContain("label: '返回汇总与放行'")
    expect(viewSource).toContain('name="quote-route"')
    expect(viewSource).toContain('quote-route-enter-active')
    expect(viewSource).toContain('button:not(:disabled):hover')
    expect(viewSource).toContain('transform: translateY(-2px)')
    expect(viewSource).toContain('font-size: 13px !important')
    expect(viewSource).toContain('font-size: 12px !important')
    expect(viewSource).toContain('@media (prefers-reduced-motion: reduce)')
    expect(createDialogSource).toContain('.quote-primary-button,.quote-secondary-button{font-size:13px}')
    expect(createDialogSource).toContain('.quote-segment-pills span{font-size:11px}')
    expect(createDialogSource).toContain('.quote-primary-button:hover,.quote-secondary-button:hover')
  })

  it('does not import external prototype CDNs and uses the protected internal-quote API adapter', () => {
    const combined = [viewSource, homeSource, collaborationSource, activitySource, sectionEditorSource, summarySource, exportSource].join('\n')
    expect(combined).not.toMatch(/cdn\.tailwindcss|fonts\.googleapis|material-symbols|lh3\.googleusercontent/)
    expect(apiSource).toContain("'/internal-quotes'")
    expect(apiSource).toContain("'/internal-quotes/business-owners'")
    expect(apiSource).toContain('include_sections: true')
    expect(apiSource).toContain('saveSection(quoteId')
    expect(apiSource).toContain('previewImport(quoteId')
    expect(apiSource).toContain('reviewFinal(quoteId')
    expect(storeSource).toContain('internalQuoteApi.list')
    expect(storeSource).not.toContain('createInitialInternalQuotes')
  })
})
