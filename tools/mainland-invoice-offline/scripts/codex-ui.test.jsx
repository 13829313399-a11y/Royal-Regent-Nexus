// @vitest-environment jsdom
import { it, expect, vi, beforeEach, afterEach } from 'vitest'
import { render, screen, fireEvent, waitFor, act, cleanup } from '@testing-library/react'
import CodexWorkbench from '../src/pages/CodexWorkbench.tsx'

const mock = vi.hoisted(() => ({ parse: vi.fn(), cancel: vi.fn(), asset: vi.fn(), generate: vi.fn() }))
vi.mock('../src/lib/codexOffThread.js', () => ({ parseCodexOffThread: mock.parse, cancelCodexParsing: mock.cancel }))
vi.mock('../src/lib/loadAsset.js', () => ({ loadAsset: mock.asset }))
vi.mock('../src/lib/codexImport.js', () => ({ sourceRowsForRecord: () => [{ row: 25, cells: [{ address: 'S25', value: '澳大利亚' }, { address: 'T25', value: 11.4 }, { address: 'X25', value: 4560, display: '1912/6/25' }] }] }))
vi.mock('../src/lib/codexExport.js', () => ({ generateCodexOutputs: mock.generate, buildCodexAuditCsv: () => '\ufeff票号,说明\nSYN00018,核对通过' }))
const example = () => ({ id: 'source1', name: '合成.xlsx', kind: 'hxg', status: 'ready', records: [{ id: 'r1', invNo: 'SYN00018', customer: 'SHUSHUPAPA', amount: 123.45, currency: 'USD', sourceSheet: '已出发票', sourceRows: [25], date: '2026-09-30', lines: [] }, { id: 'r2', invNo: 'SYN00019', customer: 'SHUSHUPAPA', amount: 50, currency: 'USD', sourceSheet: '已出发票', sourceRows: [26], date: '2026-09-30', lines: [] }], issues: [{ id: 'w1', recordId: null, recordIds: ['r1', 'r2'], severity: 'warning', category: '数据核对', text: '同组两张票需要核对', invNo: 'SYN00018', sheet: '已出发票', row: 25 }], buffer: new ArrayBuffer(2) })
const upload = async (name = '合成.xlsx') => act(async () => fireEvent.change(screen.getByLabelText('codex导入资料'), { target: { files: [new File(['x'], name)] } }))
beforeEach(() => { localStorage.clear(); vi.clearAllMocks(); mock.parse.mockResolvedValue(example()); mock.asset.mockResolvedValue(new ArrayBuffer(2)); mock.generate.mockResolvedValue({ files: [{ name: '单票.xlsx', buffer: new ArrayBuffer(2) }], notes: [] }) })
afterEach(cleanup)

it('一个关联多票的提示在每张票显示，核对结论保存且不改金额', async () => {
  render(<CodexWorkbench />); await upload()
  fireEvent.click(screen.getByRole('button', { name: '发票与追溯' }))
  expect(screen.getAllByText('需核对').filter(el => el.tagName === 'SPAN')).toHaveLength(2)
  fireEvent.click(screen.getByRole('button', { name: 'SYN00018' }))
  expect(screen.getByRole('dialog').textContent).toContain('T25')
  expect(screen.getByRole('dialog').textContent).toContain('4560')
  expect(screen.getByRole('dialog').textContent).toContain('原格式显示：1912/6/25')
  fireEvent.click(screen.getByRole('button', { name: '进入异常核对' }))
  fireEvent.change(screen.getByLabelText('核对说明w1'), { target: { value: '与原票一致' } })
  fireEvent.click(screen.getByRole('button', { name: '标记已核对' }))
  expect(JSON.parse(localStorage.getItem('codex-invoice-review-v1')).w1).toMatchObject({ status: 'reviewed', note: '与原票一致' })
  fireEvent.click(screen.getByRole('button', { name: '发票与追溯' }))
  expect(screen.getAllByText('已核对').length).toBeGreaterThanOrEqual(2)
  expect(screen.getByText('123.45')).toBeTruthy()
})

it('导入期间不能勾选或清空造成任务悬挂，取消后可以再次导入', async () => {
  render(<CodexWorkbench />); await upload()
  let finish; mock.parse.mockImplementationOnce(() => new Promise((resolve) => { finish = resolve }))
  await upload('第二份.xlsx')
  await waitFor(() => expect(mock.parse).toHaveBeenCalledTimes(2))
  fireEvent.click(screen.getByRole('button', { name: '发票与追溯' }))
  expect(screen.getByRole('button', { name: '清空选择' }).disabled).toBe(true)
  expect(screen.getByLabelText('选择发票SYN00018').disabled).toBe(true)
  expect(screen.getByRole('combobox', { name: '华兴打印格式' }).disabled).toBe(true)
  fireEvent.click(screen.getByRole('button', { name: '取消导入' }))
  await act(async () => finish({ ...example(), id: 'late', name: '第二份.xlsx' }))
  expect(screen.queryByText('第二份.xlsx')).toBeNull()
  expect(screen.getByRole('button', { name: '清空选择' }).disabled).toBe(false)
})

it('在演示文件载入时取消，不会晚到后重新开始导入', async () => {
  let finish; mock.asset.mockImplementationOnce(() => new Promise((resolve) => { finish = resolve }))
  render(<CodexWorkbench />)
  fireEvent.click(screen.getByRole('button', { name: '载入现有资料演示' }))
  fireEvent.click(screen.getByRole('button', { name: '取消导入' }))
  await act(async () => finish(new ArrayBuffer(2)))
  expect(mock.parse).not.toHaveBeenCalled()
  expect(screen.queryByRole('status')).toBeNull()
})

it('筛选后的生成只使用明确勾选的票号，修改选择清理旧输出', async () => {
  render(<CodexWorkbench />); await upload()
  fireEvent.click(screen.getByRole('button', { name: '发票与追溯' }))
  fireEvent.click(screen.getByRole('button', { name: '清空选择' }))
  fireEvent.change(screen.getByLabelText('搜索发票'), { target: { value: 'SYN00018' } })
  fireEvent.click(screen.getByRole('button', { name: '选中筛选结果' }))
  fireEvent.click(screen.getByRole('button', { name: '生成发票 Excel' }))
  await waitFor(() => expect(screen.getByText('单票.xlsx')).toBeTruthy())
  expect([...mock.generate.mock.calls[0][1].selectedRecordIds]).toEqual(['r1'])
  fireEvent.click(screen.getByRole('button', { name: '发票与追溯' }))
  fireEvent.click(screen.getByRole('button', { name: '清空选择' }))
  fireEvent.click(screen.getByRole('button', { name: '生成与下载' }))
  expect(screen.queryByText('单票.xlsx')).toBeNull()
})

it('未知金额不记作0，生成后回填的票面金额及时显示', async () => {
  const source = example(); source.records = [{ ...source.records[0], amount: null, amountLabel: '生成后按票面核对' }]
  mock.parse.mockResolvedValue(source)
  mock.generate.mockImplementation(async (sessions) => { sessions[0].records[0].amount = 123.45; return { files: [{ name: '票.xlsx', buffer: new ArrayBuffer(2) }], notes: [] } })
  render(<CodexWorkbench />); await upload()
  fireEvent.click(screen.getByRole('button', { name: '发票与追溯' }))
  expect(screen.getByText(/1 张金额待生成后核对/)).toBeTruthy()
  fireEvent.click(screen.getByRole('button', { name: '生成发票 Excel' }))
  await waitFor(() => expect(screen.getByText('票.xlsx')).toBeTruthy())
  fireEvent.click(screen.getByRole('button', { name: '发票与追溯' }))
  expect(screen.getByText('123.45')).toBeTruthy()
  expect(screen.queryByText(/1 张金额待生成后核对/)).toBeNull()
})

it('华兴打印格式传到生成器，切换格式后清理旧文件并重新生成', async () => {
  render(<CodexWorkbench />); await upload()
  fireEvent.click(screen.getByRole('button', { name: '生成与下载' }))
  expect(screen.getByRole('combobox', { name: '华兴打印格式' }).value).toBe('auto')
  fireEvent.click(screen.getByRole('button', { name: '生成发票 Excel' }))
  await waitFor(() => expect(screen.getByText('单票.xlsx')).toBeTruthy())
  expect(mock.generate.mock.calls[0][1].hxgPrintMode).toBe('auto')
  fireEvent.change(screen.getByRole('combobox', { name: '华兴打印格式' }), { target: { value: 'preprinted' } })
  expect(screen.queryByText('单票.xlsx')).toBeNull()
  fireEvent.click(screen.getByRole('button', { name: '生成发票 Excel' }))
  await waitFor(() => expect(screen.getByText('单票.xlsx')).toBeTruthy())
  expect(mock.generate.mock.calls[1][1].hxgPrintMode).toBe('preprinted')
  fireEvent.change(screen.getByRole('combobox', { name: '华兴打印格式' }), { target: { value: 'full' } })
  expect(screen.queryByText('单票.xlsx')).toBeNull()
  fireEvent.click(screen.getByRole('button', { name: '生成发票 Excel' }))
  await waitFor(() => expect(screen.getByText('单票.xlsx')).toBeTruthy())
  expect(mock.generate.mock.calls[2][1].hxgPrintMode).toBe('full')
})

it('未选择华兴票时不显示华兴打印选项', async () => {
  const source = example(); source.kind = 'hdd'; mock.parse.mockResolvedValue(source)
  render(<CodexWorkbench />); await upload()
  fireEvent.click(screen.getByRole('button', { name: '生成与下载' }))
  expect(screen.queryByRole('combobox', { name: '华兴打印格式' })).toBeNull()
})
